import { HTTP_STATUS_CODES } from "./http-statuses";

/** Statuses whose responses must never carry a body (Fetch spec "null body status"). */
export const NULL_BODY_STATUSES = new Set([101, 103, 204, 205, 304]);

/** Statuses that should include a Location header when emitted. */
export const REDIRECT_STATUSES = new Set([301, 302, 303, 307, 308]);

/** The Fetch `Response` constructor only accepts 200–599, so only those can be mocked live. */
export function isMockableStatus(code: string): boolean {
  if (!/^\d{3}$/.test(code)) return false;
  const n = Number(code);
  return n >= 200 && n <= 599;
}

/** Recommended extra headers when emitting a given status. */
export function recommendedHeaders(code: number): Record<string, string> {
  if (code === 401) return { "WWW-Authenticate": 'Bearer realm="api"' };
  if (code === 405) return { Allow: "GET, POST" };
  if (code === 429 || code === 503) return { "Retry-After": "60" };
  if (code === 426) return { Upgrade: "HTTP/2.0", Connection: "Upgrade" };
  return {};
}

export interface StatusSnippets {
  express: string;
  nextjs: string;
  nginx: string;
  curl: string;
}

function statusName(code: string): string {
  const info = HTTP_STATUS_CODES[code];
  return info ? info.title.replace(`${code} `, "") : "Status";
}

export function getStatusSnippets(code: string): StatusSnippets {
  const n = Number(code);
  const name = statusName(code);
  const headers = recommendedHeaders(n);
  const isRedirect = REDIRECT_STATUSES.has(n);
  const nullBody = NULL_BODY_STATUSES.has(n);
  const isInformational = n < 200;
  const isVendor = n === 499 || (n >= 520 && n <= 526);

  const headerEntries = Object.entries(headers);
  const vendorNote = isVendor
    ? `// Note: ${code} is normally generated by ${n === 499 ? "Nginx" : "Cloudflare"}, not your app.\n// Emitting it yourself is only useful for testing client error handling.\n`
    : "";

  // ---- Express ----
  let express: string;
  if (isInformational) {
    express = `// ${code} ${name} is an interim (1xx) response handled by Node's HTTP layer.\n// Node.js emits it via res.writeContinue() / res.writeEarlyHints():\napp.get("/", (req, res) => {\n  ${n === 103 ? 'res.writeEarlyHints({ link: "</styles.css>; rel=preload; as=style" });' : n === 100 ? "res.writeContinue();" : "// Rarely emitted manually."}\n  res.status(200).send("OK");\n});`;
  } else if (isRedirect) {
    express = `app.get("/old-path", (req, res) => {\n  res.redirect(${n}, "/new-path");\n});`;
  } else {
    const setHeaders = headerEntries.map(([k, v]) => `\n    .set(${JSON.stringify(k)}, ${JSON.stringify(v)})`).join("");
    const body = nullBody ? "\n    .end();" : `\n    .json({ error: ${JSON.stringify(name)}, status: ${n} });`;
    express = `${vendorNote}app.get("/api/resource", (req, res) => {\n  res\n    .status(${n})${setHeaders}${body}\n});`;
  }

  // ---- Next.js App Router route handler ----
  let nextjs: string;
  if (isInformational) {
    nextjs = `// Route Handlers cannot return 1xx responses: the Response constructor\n// only accepts status codes 200-599. ${code} ${name} is emitted by the server/CDN layer.`;
  } else if (isRedirect) {
    nextjs = `// app/old-path/route.ts\nexport function GET(request: Request) {\n  return Response.redirect(new URL("/new-path", request.url), ${n});\n}`;
  } else {
    const headerObj = headerEntries.length
      ? `,\n    headers: { ${headerEntries.map(([k, v]) => `${JSON.stringify(k)}: ${JSON.stringify(v)}`).join(", ")} }`
      : "";
    nextjs = nullBody
      ? `${vendorNote}// app/api/resource/route.ts\nexport function GET() {\n  // ${n} must not include a response body\n  return new Response(null, {\n    status: ${n}${headerObj}\n  });\n}`
      : `${vendorNote}// app/api/resource/route.ts\nexport function GET() {\n  return Response.json(\n    { error: ${JSON.stringify(name)}, status: ${n} },\n    {\n      status: ${n}${headerObj.replace(/\n {4}/g, "\n      ")}\n    }\n  );\n}`;
  }

  // ---- Nginx ----
  let nginx: string;
  if (isInformational) {
    nginx = `# Nginx handles ${code} ${name} automatically at the protocol level.\n# Example: enable HTTP/2 + early hints (Nginx >= 1.29):\n# early_hints on;`;
  } else if (isRedirect) {
    nginx = `location /old-path {\n    return ${n} https://$host/new-path;\n}`;
  } else if (n === 499) {
    nginx = `# 499 is logged by Nginx when the client disconnects first.\n# Give slow upstreams more time and keep the connection to the client:\nlocation /api/ {\n    proxy_pass http://127.0.0.1:3000;\n    proxy_read_timeout 120s;\n    proxy_ignore_client_abort on;\n}`;
  } else {
    const addHeaders = headerEntries.map(([k, v]) => `\n    add_header ${k} '${v}' always;`).join("");
    nginx = `location /api/resource {${addHeaders}\n    return ${n}${nullBody ? "" : ` '{"error":"${name.replace(/'/g, "")}","status":${n}}'`};\n}`;
  }

  // ---- curl ----
  const curl = `# Inspect the status line and headers of any endpoint:\ncurl -sS -o /dev/null -w "%{http_code}\\n" https://your-api.example/endpoint\n\n# Reproduce ${code} instantly with the Castov mock endpoint:\ncurl -i https://castov.com/api/mock/${isMockableStatus(code) ? code : "200"}`;

  return { express, nextjs, nginx, curl };
}

export interface StatusComparison {
  other: string;
  summary: string;
}

/** Hand-written comparisons for the status pairs developers confuse most often. */
const COMPARISON_PAIRS: [string, string, string][] = [
  ["401", "403", "401 means the server does not know who you are (missing or invalid credentials) — authenticate and retry. 403 means it knows who you are but you are not allowed — retrying with the same credentials will never work."],
  ["301", "302", "301 is permanent: browsers cache it and search engines transfer ranking signals to the new URL. 302 is temporary: the original URL stays indexed."],
  ["301", "308", "Both are permanent. 301 lets clients change POST to GET when following the redirect; 308 strictly preserves the method and body."],
  ["302", "307", "Both are temporary. 302 allows clients to switch POST to GET; 307 guarantees the same method and payload are re-sent."],
  ["302", "303", "303 explicitly tells the client to follow up with GET (Post/Redirect/Get). 302 is ambiguous about the method for historic reasons."],
  ["400", "422", "400 means the request is syntactically malformed (invalid JSON, bad framing). 422 means it parsed fine but failed validation rules (e.g. Zod or Pydantic errors)."],
  ["404", "410", "404 means the resource is not found and may come back. 410 tells clients and search engines it was removed permanently, so it is de-indexed faster."],
  ["500", "503", "500 is an unexpected bug or crash. 503 is a deliberate, temporary 'not now' (maintenance or overload) and should include Retry-After."],
  ["502", "504", "502 means the upstream answered with an invalid response or refused the connection. 504 means the upstream never answered in time."],
  ["502", "503", "502 comes from a proxy that got a bad answer from upstream. 503 is the service itself (or the proxy) saying it is temporarily unavailable."],
  ["429", "503", "429 targets one client that exceeded its rate limit. 503 means the whole service is unavailable for everyone."],
  ["403", "404", "Some APIs return 404 instead of 403 to avoid revealing that a private resource exists (security through non-disclosure)."],
  ["200", "204", "200 returns a body; 204 confirms success with no body at all — clients must not try to parse JSON from a 204."],
  ["200", "201", "201 signals a new resource was created and should include a Location header pointing to it; 200 is a generic success."],
  ["499", "504", "499 means the client gave up waiting and closed the connection; 504 means the proxy gave up waiting for the upstream."],
  ["522", "524", "522 is a TCP connection timeout to the origin. 524 means the connection succeeded but the origin took longer than 100 seconds to respond."],
  ["520", "502", "520 is Cloudflare's catch-all for an empty or unexpected origin response; 502 is the generic gateway error from other proxies."],
  ["412", "428", "412 means a conditional header (If-Match) did not match. 428 means the server requires a conditional header and none was sent."],
  ["407", "401", "407 asks for credentials for an intermediate proxy (Proxy-Authorization); 401 asks for credentials for the origin server (Authorization)."],
];

export function getStatusComparisons(code: string): StatusComparison[] {
  const out: StatusComparison[] = [];
  for (const [a, b, summary] of COMPARISON_PAIRS) {
    if (a === code && HTTP_STATUS_CODES[b]) out.push({ other: b, summary });
    else if (b === code && HTTP_STATUS_CODES[a]) out.push({ other: a, summary });
  }
  return out;
}
